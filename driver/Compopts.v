(** Compilation options *)

(** This file collects Coq functions to query the command-line
  options that influence the code generated by the verified
  part of CompCert.   These functions are mapped by extraction
  to accessors for the flags in [Clflags.ml]. *)

(** Flag [-Os].  For instruction selection (mainly). *)
Parameter optim_for_size: unit -> bool.

(** Flag [-ffloat-const-prop].  For value analysis and constant propagation. *)
Parameter propagate_float_constants: unit -> bool.
Parameter generate_float_constants: unit -> bool.

(** For value analysis.  Currently always false. *)
Parameter va_strict: unit -> bool.

(** Flag -ftailcalls.  For tail call optimization. *)
Parameter optim_tailcalls: unit -> bool.

(** Flag -fconstprop.  For constant propagation. *)
Parameter optim_constprop: unit -> bool.

(** Flag -fcse.  For common subexpression elimination. *)
Parameter optim_CSE: unit -> bool.

(** Flag -fredundancy.  For dead code elimination. *)
Parameter optim_redundancy: unit -> bool.

(** Flag -fthumb.  For the ARM back-end. *)
Parameter thumb: unit -> bool.

(** Flag -g.  For insertion of debugging information. *)
Parameter debug: unit -> bool.

(** Default-disabled experimental transformations. Their semantic preservation
    is proved for every value of these computational options. *)
Parameter experimental_scalar: unit -> bool.
Parameter experimental_unroll4: unit -> bool.
Parameter experimental_cleanup: unit -> bool.
Parameter experimental_unswitch: unit -> bool.
Parameter experimental_select: unit -> bool.
Parameter experimental_hoist: unit -> bool.
Parameter experimental_schedule: unit -> bool.
Parameter experimental_loadforward: unit -> bool.
Parameter experimental_storeelim: unit -> bool.
Parameter experimental_vectorize: unit -> bool.
Parameter experimental_licm: unit -> bool.
Parameter experimental_strength: unit -> bool.
Parameter experimental_peel: unit -> bool.
Parameter experimental_preheader: unit -> bool.
Parameter experimental_memvector: unit -> bool.
Parameter experimental_fusion: unit -> bool.
Parameter experimental_interchange: unit -> bool.
Parameter experimental_tile: unit -> bool.
Parameter experimental_tile2d: unit -> bool.
Parameter experimental_memoryneon: unit -> bool.
